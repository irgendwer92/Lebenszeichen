"""Converts a fixed-width BDF font (X11 misc-fixed, public domain) into a C
table for the satellite's display: one byte per row (MSB left, width at most
8), each glyph the full cell, codepoints sorted for a binary search.

    bdf2c.py 6x10.bdf font_small > main/font_small.c
"""
import sys

# What the display needs: ASCII, Latin-1, and a few signs.
WANTED = (
    list(range(0x20, 0x7F))
    + list(range(0xA0, 0x100))
    + [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x201E, 0x2022,
       0x2026, 0x20AC, 0x2190, 0x2192, 0x2713, 0x2717]
)


# Signs the fonts lack, drawn here, by cell height.
EXTRA = {
    10: {
        0x2713: ["......", ".....#", ".....#", "....#.", "....#.",
                 "#..#..", ".#.#..", "..#...", "......", "......"],
        0x2717: ["......", "......", "#...#.", ".#.#..", "..#...",
                 ".#.#..", "#...#.", "......", "......", "......"],
    },
    14: {
        0x2713: [".......", ".......", "......#", "......#", ".....##",
                 ".....#.", "....##.", "##..#..", ".####..", "..##...",
                 "..#....", ".......", ".......", "......."],
        0x2717: [".......", ".......", ".......", "##...##", ".##.##.",
                 "..###..", "...#...", "..###..", ".##.##.", "##...##",
                 ".......", ".......", ".......", "......."],
    },
}


def drawn(art):
    return [sum(0x80 >> i for i, ch in enumerate(row) if ch == "#") for row in art]


def parse(path):
    glyphs, box = {}, None
    with open(path, encoding="latin-1") as f:
        lines = iter(f.read().splitlines())
    for line in lines:
        if line.startswith("FONTBOUNDINGBOX"):
            box = tuple(int(v) for v in line.split()[1:])
        elif line.startswith("STARTCHAR"):
            cp, bbx, rows = None, None, []
            for line in lines:
                if line.startswith("ENCODING"):
                    cp = int(line.split()[1])
                elif line.startswith("BBX"):
                    bbx = tuple(int(v) for v in line.split()[1:])
                elif line == "BITMAP":
                    for line in lines:
                        if line == "ENDCHAR":
                            break
                        rows.append(int(line, 16))
                    break
            glyphs[cp] = (bbx, rows)
    return box, glyphs


def cell(box, bbx, rows):
    fw, fh, fx, fy = box
    w, h, x, y = bbx
    out = [0] * fh
    nbytes = (w + 7) // 8
    for i, r in enumerate(rows):
        line = fh - (y - fy) - h + i  # row in the cell, from the top
        if not 0 <= line < fh:
            continue
        for b in range(w):
            if r & (1 << (nbytes * 8 - 1 - b)):
                col = x - fx + b
                if 0 <= col < 8:
                    out[line] |= 0x80 >> col
    return out


def main():
    path, name = sys.argv[1], sys.argv[2]
    box, glyphs = parse(path)
    fw, fh = box[0], box[1]
    if fw > 8:
        sys.exit("width above 8")
    extra = EXTRA.get(fh, {})
    cps = [c for c in WANTED if c in glyphs or c in extra]
    print("/* SPDX-License-Identifier: LicenseRef-Public-Domain AND (LGPL-3.0-or-later WITH LicenseRef-Lebenszeichen-static-linking-exception) */")
    print(f"/* Generated by tools/bdf2c.py from {path.split('/')[-1]} (X11 misc-fixed,")
    print(" * public domain: \"Share and enjoy.\"); U+2713 and U+2717 drawn in")
    print(" * tools/bdf2c.py. Do not edit. */")
    print('#include "font.h"\n')
    print(f"static const uint16_t cps[{len(cps)}] = {{")
    for i in range(0, len(cps), 10):
        print("    " + ", ".join(f"0x{c:04X}" for c in cps[i:i + 10]) + ",")
    print("};\n")
    print(f"static const uint8_t bits[{len(cps)} * {fh}] = {{")
    for c in cps:
        rows = cell(box, *glyphs[c]) if c in glyphs else drawn(extra[c])
        print("    " + ", ".join(f"0x{r:02X}" for r in rows) + f", /* U+{c:04X} */")
    print("};\n")
    print(f"const lz_font {name} = {{ {fw}, {fh}, {len(cps)}, cps, bits }};")


main()
